package codegen

import (
	"fmt"
	"sort"
	"strings"
)

func emitGoFile(widget Widget, packageName, formaUIImport string) string {
	if widget.Kind == "compound" {
		return emitCompound(widget, packageName, formaUIImport)
	}
	return emitLeaf(widget, packageName, formaUIImport)
}

func emitLeaf(widget Widget, packageName, formaUIImport string) string {
	recv := receiverName(widget.Name)
	var props strings.Builder
	for _, p := range widget.Props {
		fmt.Fprintf(&props, "\t%s %s\n", p.Name, p.GoType)
	}
	return strings.Join([]string{
		`// Code generated by forma generate; DO NOT EDIT.`,
		``,
		`package ` + packageName,
		``,
		`import (`,
		`	"context"`,
		``,
		`	ui "` + formaUIImport + `"`,
		`)`,
		``,
		`type ` + widget.Name + ` struct {`,
		`	ui.BaseComponent`,
		props.String() + `}`,
		``,
		fmt.Sprintf(`func (%s %s) With(children ...ui.Component) %s {`, recv, widget.Name, widget.Name),
		fmt.Sprintf(`	%s.BaseComponent = %s.BaseComponent.With(children...)`, recv, recv),
		fmt.Sprintf(`	return %s`, recv),
		`}`,
		``,
		fmt.Sprintf(`func (%s %s) Or(fallback ...ui.Component) %s {`, recv, widget.Name, widget.Name),
		fmt.Sprintf(`	%s.BaseComponent = %s.BaseComponent.Or(fallback...)`, recv, recv),
		fmt.Sprintf(`	return %s`, recv),
		`}`,
		``,
		fmt.Sprintf(`func (%s %s) Render(ctx context.Context) *ui.Node {`, recv, widget.Name),
		fmt.Sprintf(`	node := %s.BaseComponent.Render(ctx)`, recv),
		fmt.Sprintf(`	node.Type = %q`, widget.Name),
		fmt.Sprintf(`	node.Props = %s`, recv),
		`	return node`,
		`}`,
		``,
	}, "\n")
}

func emitCompound(widget Widget, packageName, formaUIImport string) string {
	recv := receiverName(widget.Name)
	var props strings.Builder
	for _, p := range widget.Props {
		fmt.Fprintf(&props, "\t%s %s\n", p.Name, p.GoType)
	}
	var slots strings.Builder
	for _, s := range widget.Slots {
		fmt.Fprintf(&slots, "\t%s ui.Component\n", s.Field)
	}
	var putSlots strings.Builder
	for _, s := range widget.Slots {
		fmt.Fprintf(&putSlots,
			"\tui.PutSlot(slots, ui.SlotKeyFromField(%q), ui.RenderComponentSlot(ctx, %s.%s))\n",
			s.Field, recv, s.Field,
		)
	}
	return strings.Join([]string{
		`// Code generated by forma generate; DO NOT EDIT.`,
		``,
		`package ` + packageName,
		``,
		`import (`,
		`	"context"`,
		``,
		`	ui "` + formaUIImport + `"`,
		`)`,
		``,
		`type ` + widget.Name + ` struct {`,
		`	ui.WidgetMeta`,
		props.String() + slots.String() + `}`,
		``,
		fmt.Sprintf(`func (%s %s) Render(ctx context.Context) *ui.Node {`, recv, widget.Name),
		`	slots := map[string][]*ui.Node{}`,
		strings.TrimSuffix(putSlots.String(), "\n"),
		`	if len(slots) == 0 {`,
		`		slots = nil`,
		`	}`,
		`	return &ui.Node{`,
		fmt.Sprintf(`		Type:  %q,`, widget.Name),
		fmt.Sprintf(`		Key:   %s.Key,`, recv),
		fmt.Sprintf(`		Class: %s.Class,`, recv),
		fmt.Sprintf(`		Props: %s,`, recv),
		`		Slots: slots,`,
		`	}`,
		`}`,
		``,
	}, "\n")
}

func emitRegistry(widgets []Widget) string {
	imports := map[string]map[string]struct{}{}
	for _, w := range widgets {
		set := imports[w.ImportPath]
		if set == nil {
			set = map[string]struct{}{}
			imports[w.ImportPath] = set
		}
		if w.Kind == "leaf" {
			set[w.ExportName] = struct{}{}
		} else {
			set[w.RootExport] = struct{}{}
			for _, s := range w.Slots {
				set[s.ExportName] = struct{}{}
			}
		}
	}

	paths := make([]string, 0, len(imports))
	for p := range imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var importLines []string
	for _, p := range paths {
		names := make([]string, 0, len(imports[p]))
		for n := range imports[p] {
			names = append(names, n)
		}
		sort.Strings(names)
		importLines = append(importLines, fmt.Sprintf(`import { %s } from %q;`, strings.Join(names, ", "), p))
	}

	var entries []string
	for _, w := range widgets {
		if w.Kind == "leaf" {
			entries = append(entries, fmt.Sprintf(`  %q: { component: %s },`, w.Name, w.ExportName))
			continue
		}
		var parts []string
		for _, s := range w.Slots {
			parts = append(parts, fmt.Sprintf(`      %q: %s,`, s.Field, s.ExportName))
		}
		entries = append(entries, strings.Join([]string{
			fmt.Sprintf(`  %q: {`, w.Name),
			fmt.Sprintf(`    component: %s,`, w.RootExport),
			`    slots: {`,
			strings.Join(parts, "\n"),
			`    },`,
			`  },`,
		}, "\n"))
	}

	lines := []string{
		`// Code generated by forma generate; DO NOT EDIT.`,
		``,
		`import type { ComponentType } from "react";`,
		``,
	}
	lines = append(lines, importLines...)
	lines = append(lines,
		``,
		`export type RegistryEntry = {`,
		`  component: ComponentType<Record<string, unknown>>;`,
		`  slots?: Record<string, ComponentType<Record<string, unknown>>>;`,
		`};`,
		``,
		`export const registry: Record<string, RegistryEntry> = {`,
	)
	lines = append(lines, entries...)
	lines = append(lines, `};`, ``)
	return strings.Join(lines, "\n")
}

func receiverName(typeName string) string {
	if typeName == "" {
		return "v"
	}
	ch := strings.ToLower(typeName[:1])
	if ch == typeName[:1] {
		return "v"
	}
	return ch
}
