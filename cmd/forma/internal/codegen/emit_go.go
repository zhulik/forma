package codegen

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/dave/jennifer/jen"

	"github.com/zhulik/forma/cmd/forma/pkg/ident"
	"github.com/zhulik/forma/fn"
)

func emitGoFile(widget Widget, packageName, formaUIImport string) string {
	if widget.Kind == "compound" {
		return emitCompound(widget, packageName, formaUIImport)
	}
	return emitLeaf(widget, packageName, formaUIImport)
}

func emitLeaf(widget Widget, packageName, formaUIImport string) string {
	recv := ident.ReceiverName(widget.Name)
	f := newGenFile(packageName, formaUIImport)

	fields := append(
		[]jen.Code{jen.Qual(formaUIImport, "BaseComponent")},
		fn.Map(widget.Props, func(p PropField) jen.Code {
			return jen.Id(p.Name).Add(goTypeExpr(formaUIImport, p.GoType))
		})...,
	)
	f.Type().Id(widget.Name).Struct(fields...)

	f.Func().Params(jen.Id(recv).Id(widget.Name)).Id("With").Params(
		jen.Id("children").Op("...").Qual(formaUIImport, "Component"),
	).Id(widget.Name).Block(
		jen.Id(recv).Dot("BaseComponent").Op("=").Id(recv).Dot("BaseComponent").Dot("With").Call(jen.Id("children").Op("...")),
		jen.Return(jen.Id(recv)),
	)
	f.Line()

	f.Func().Params(jen.Id(recv).Id(widget.Name)).Id("Or").Params(
		jen.Id("fallback").Op("...").Qual(formaUIImport, "Component"),
	).Id(widget.Name).Block(
		jen.Id(recv).Dot("BaseComponent").Op("=").Id(recv).Dot("BaseComponent").Dot("Or").Call(jen.Id("fallback").Op("...")),
		jen.Return(jen.Id(recv)),
	)
	f.Line()

	f.Func().Params(jen.Id(recv).Id(widget.Name)).Id("Render").Params(
		jen.Id("ctx").Qual("context", "Context"),
	).Op("*").Qual(formaUIImport, "Node").Block(
		jen.Id("node").Op(":=").Id(recv).Dot("BaseComponent").Dot("Render").Call(jen.Id("ctx")),
		jen.Id("node").Dot("Type").Op("=").Lit(widget.Name),
		jen.Id("node").Dot("Props").Op("=").Id(recv),
		jen.Return(jen.Id("node")),
	)

	return renderFile(f)
}

func emitCompound(widget Widget, packageName, formaUIImport string) string {
	recv := ident.ReceiverName(widget.Name)
	f := newGenFile(packageName, formaUIImport)

	fields := append(
		[]jen.Code{jen.Qual(formaUIImport, "WidgetMeta")},
		fn.Map(widget.Props, func(p PropField) jen.Code {
			return jen.Id(p.Name).Add(goTypeExpr(formaUIImport, p.GoType))
		})...,
	)
	fields = append(fields, fn.Map(widget.Slots, func(s SlotField) jen.Code {
		return jen.Id(s.Field).Qual(formaUIImport, "Component")
	})...)
	f.Type().Id(widget.Name).Struct(fields...)

	putSlots := fn.Map(widget.Slots, func(s SlotField) jen.Code {
		return jen.Qual(formaUIImport, "PutSlot").Call(
			jen.Id("slots"),
			jen.Qual(formaUIImport, "SlotKeyFromField").Call(jen.Lit(s.Field)),
			jen.Qual(formaUIImport, "RenderComponentSlot").Call(
				jen.Id("ctx"),
				jen.Id(recv).Dot(s.Field),
			),
		)
	})

	body := []jen.Code{
		jen.Id("slots").Op(":=").Map(jen.String()).Index().Op("*").Qual(formaUIImport, "Node").Values(),
	}
	body = append(body, putSlots...)
	body = append(body,
		jen.If(jen.Len(jen.Id("slots")).Op("==").Lit(0)).Block(
			jen.Id("slots").Op("=").Nil(),
		),
		jen.Return(jen.Op("&").Qual(formaUIImport, "Node").Custom(jen.Options{
			Open:      "{",
			Close:     "}",
			Multi:     true,
			Separator: ",",
		},
			jen.Id("Type").Op(":").Lit(widget.Name),
			jen.Id("Key").Op(":").Id(recv).Dot("Key"),
			jen.Id("Class").Op(":").Id(recv).Dot("Class"),
			jen.Id("Props").Op(":").Id(recv),
			jen.Id("Slots").Op(":").Id("slots"),
		)),
	)

	f.Func().Params(jen.Id(recv).Id(widget.Name)).Id("Render").Params(
		jen.Id("ctx").Qual("context", "Context"),
	).Op("*").Qual(formaUIImport, "Node").Block(body...)

	return renderFile(f)
}

func newGenFile(packageName, formaUIImport string) *jen.File {
	f := jen.NewFile(packageName)
	f.HeaderComment("Code generated by forma generate; DO NOT EDIT.")
	f.ImportAlias(formaUIImport, "ui")
	return f
}

func goTypeExpr(formaUIImport, goType string) *jen.Statement {
	switch goType {
	case "string":
		return jen.String()
	case "bool":
		return jen.Bool()
	case "float64":
		return jen.Float64()
	case goTypeClickCallback:
		return jen.Func().Params(jen.Id("ctx").Qual(formaUIImport, "Context"))
	case goTypeChangeCallback:
		return jen.Func().Params(
			jen.Id("ctx").Qual(formaUIImport, "Context"),
			jen.Id("value").String(),
		)
	case goTypeCheckedCallback:
		return jen.Func().Params(
			jen.Id("ctx").Qual(formaUIImport, "Context"),
			jen.Id("checked").Bool(),
		)
	default:
		return jen.Id(goType)
	}
}

func renderFile(f *jen.File) string {
	var buf bytes.Buffer
	if err := f.Render(&buf); err != nil {
		panic(fmt.Sprintf("render generated go: %v", err))
	}
	// jennifer may omit the blank line between stdlib and third-party imports;
	// restore goimports-style grouping to keep generated output conventional.
	return ensureImportGroupBlank(buf.String())
}

func ensureImportGroupBlank(src string) string {
	const needle = "\t\"context\"\n\t"
	const withBlank = "\t\"context\"\n\n\t"
	return strings.Replace(src, needle, withBlank, 1)
}
