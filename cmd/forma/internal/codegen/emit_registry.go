package codegen

import (
	"bytes"
	"fmt"
	"maps"
	"slices"
	"strings"
	"text/template"

	"github.com/zhulik/forma/fn"
)

const registryTmpl = `// Code generated by forma generate; DO NOT EDIT.

import type { ComponentType } from "react";
{{range .Imports}}
import { {{.Names}} } from {{printf "%q" .Path}};
{{- end}}

export type RegistryEntry = {
  component: ComponentType<Record<string, unknown>>;
  slots?: Record<string, ComponentType<Record<string, unknown>>>;
};

export const registry: Record<string, RegistryEntry> = {
{{- range .Entries}}
{{- if .Leaf}}
  {{printf "%q" .Name}}: { component: {{.Component}} },
{{- else}}
  {{printf "%q" .Name}}: {
    component: {{.Component}},
    slots: {
{{- range .Slots}}
      {{printf "%q" .Field}}: {{.ExportName}},
{{- end}}
    },
  },
{{- end}}
{{- end}}
};
`

type registryImport struct {
	Path  string
	Names string
}

type registryEntry struct {
	Name      string
	Leaf      bool
	Component string
	Slots     []SlotField
}

type registryData struct {
	Imports []registryImport
	Entries []registryEntry
}

type namedImport struct {
	Path string
	Name string
}

var registryTemplate = template.Must(template.New("registry").Parse(registryTmpl))

func emitRegistry(widgets []Widget) string {
	data := buildRegistryData(widgets)
	var buf bytes.Buffer
	if err := registryTemplate.Execute(&buf, data); err != nil {
		panic(fmt.Sprintf("render registry: %v", err))
	}
	return buf.String()
}

func buildRegistryData(widgets []Widget) registryData {
	pairs := fn.FlatMap(widgets, func(w Widget) []namedImport {
		return fn.Map(widgetExportNames(w), func(name string) namedImport {
			return namedImport{Path: w.ImportPath, Name: name}
		})
	})
	byPath := fn.GroupBy(pairs, func(p namedImport) string { return p.Path })
	importRows := fn.Map(slices.Sorted(maps.Keys(byPath)), func(p string) registryImport {
		names := fn.UniqSorted(fn.Map(byPath[p], func(x namedImport) string { return x.Name }))
		return registryImport{Path: p, Names: strings.Join(names, ", ")}
	})

	entries := fn.Map(widgets, func(w Widget) registryEntry {
		if w.Kind == "leaf" {
			return registryEntry{Name: w.Name, Leaf: true, Component: w.ExportName}
		}
		return registryEntry{
			Name:      w.Name,
			Component: w.RootExport,
			Slots:     w.Slots,
		}
	})

	return registryData{Imports: importRows, Entries: entries}
}

func widgetExportNames(w Widget) []string {
	if w.Kind == "leaf" {
		return []string{w.ExportName}
	}
	return append([]string{w.RootExport}, fn.Map(w.Slots, func(s SlotField) string {
		return s.ExportName
	})...)
}
